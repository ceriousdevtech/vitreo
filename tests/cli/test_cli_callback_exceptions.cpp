TEST(CallbackExceptionDispatchTest,
     X86SehHandlerReachingEnclosingSentinelLeftDispatcher) {
    // Every callback level returns to one sentinel. An x86 frame handler that
    // enters a continuation (MSVC CallCatchBlock's __except taking a
    // rethrow) can run out to an *enclosing* callback's sentinel return. That
    // return is not the handler's disposition: the handler left the
    // dispatcher, and the state must reach the enclosing level unchanged.
    // `ret 0x20` reaches the sentinel with ESP beyond the handler's four
    // arguments in one instruction, so no per-step check sees it earlier.
    constexpr vitreo::GuestAddr handler_addr = 0x21000;
    vitreo::GuestMemory memory;
    ASSERT_TRUE(memory.map_region(
        0x20000, 0x10000, vitreo::MemoryProtection::ReadWrite).is_ok());
    // mov eax,1 ; ret 0x20
    const std::array<vitreo::u8, 8> handler{
        0xb8, 0x01, 0x00, 0x00, 0x00, 0xc2, 0x20, 0x00};
    ASSERT_TRUE(memory.write_bytes(
        handler_addr, handler.data(), handler.size()).is_ok());

    for (bool enclosing : {false, true}) {
        SCOPED_TRACE(enclosing ? "ret 0x20 (enclosing return)" : "ret 0x10 (own return)");
        if (!enclosing) {
            // stdcall return of the handler's own four arguments.
            ASSERT_TRUE(memory.write_u8(handler_addr + 6, 0x10).is_ok());
        } else {
            ASSERT_TRUE(memory.write_u8(handler_addr + 6, 0x20).is_ok());
        }
        vitreo::cpu::CpuState cpu;
        cpu.init_protected_mode();
        cpu.set_sp(0x2fe00);
        cpu.seg.fs_desc.base = 0x20000;
        ASSERT_TRUE(memory.write_u32(0x20000, 0xffffffffu).is_ok());
        vitreo::winapi::ProcessManager process_mgr;
        vitreo::winapi::ThunkRegistry registry(0x70000000);
        const vitreo::u64 args[4]{0x2f000, 0x2fd00, 0x2f100, 0x2f200};
        (void)consume_seh32_handler_left_dispatcher();
        bool completed = false;
        const vitreo::u64 disposition = run_guest_callback(
            cpu, memory, registry, process_mgr, handler_addr, args, 4, false,
            &completed, GuestCallbackKind::Nested,
            /*seh_abandon_ctx_addr=*/0x2f100, /*seh_abandon_esp_min=*/0x2fd00);
        const bool left = consume_seh32_handler_left_dispatcher();
        EXPECT_TRUE(completed);
        if (enclosing) {
            EXPECT_TRUE(left);
            EXPECT_EQ(disposition, vitreo::cpu::ExceptionContinueExecution);
            // The enclosing level sees its own return with the guest's EAX.
            EXPECT_EQ(cpu.rip,
                      CALLBACK_RETURN_SENTINEL & 0xFFFFFFFFu);
            EXPECT_EQ(cpu.gpr.get32(0), 1u);
        } else {
            EXPECT_FALSE(left);
            EXPECT_EQ(disposition, 1u);
        }
    }
}
