std::vector<u8> from_base64(std::string_view text) {
    static constexpr std::string_view kAlphabet =
        "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    std::vector<u8> out;
    u32 buffer = 0;
    u32 bits = 0;
    for (char c : text) {
        if (c == '=') break;
        const auto index = kAlphabet.find(c);
        if (index == std::string_view::npos) continue;
        buffer = (buffer << 6) | static_cast<u32>(index);
        bits += 6;
        if (bits >= 8) {
            bits -= 8;
            out.push_back(static_cast<u8>((buffer >> bits) & 0xFF));
        }
    }
    return out;
}

/// The payload the fixture was built from, reproduced here rather than
/// embedded: the point of the test is that the decoder recovers *these* bytes,
/// so they are generated by the same rule the generator used — a xorshift32
/// word list, tiled — not copied out of the decoder's own output.
std::vector<u8> expected_payload() {
    u32 state = 2463534242u;
    auto next = [&state]() {
        state ^= state << 13;
        state ^= state >> 17;
        state ^= state << 5;
        return state;
    };
    std::vector<std::string> words(24);
    for (std::string& word : words) {
        word.resize(6);
        for (char& c : word) c = static_cast<char>('a' + (next() % 26));
    }
    auto tile = [&words](usize size, usize start) {
        std::string text;
        for (usize i = start; text.size() < size; ++i) text += words[i % 24] + " ";
        text.resize(size);
        return text;
    };

    const std::string block1 = tile(32768, 0);
    const std::string block2 = block1.substr(100, 16384) + tile(16384, 5);
    const std::string block3 = block1.substr(20000, 12768) + block2.substr(0, 20000);
    const std::string all = block1 + block2 + block3;
    return std::vector<u8>(all.begin(), all.begin() + 32768 * 3);
}

