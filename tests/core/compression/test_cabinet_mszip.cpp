/// @file test_cabinet_mszip.cpp
/// @brief Cabinet container parsing and MSZIP folder decompression.
///
/// The fixture is a real MSZIP cabinet — verified against cabextract when it
/// was generated — deliberately built so that the second and third CFDATA
/// blocks *open* with a long match reaching back into the previous block's
/// output. That is the one MSZIP property a plausible implementation gets
/// wrong: each block is its own complete DEFLATE stream, so inflating them
/// independently succeeds and yields correct bytes right up to the first
/// cross-block match, then silently produces garbage. A fixture whose blocks
/// happen not to reference each other passes either way and pins nothing.

