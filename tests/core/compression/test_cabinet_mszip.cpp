TEST(Cabinet, ParsesTheContainerStructures) {
    const std::vector<u8> image = from_base64(kCabinetBase64);
    auto parsed = cabinet::Cabinet::parse(std::span<const u8>(image.data(), image.size()));
    ASSERT_TRUE(parsed.is_ok());

    const cabinet::Cabinet& cab = parsed.value();
    EXPECT_EQ(cab.header().folder_count, 1);
    EXPECT_EQ(cab.header().file_count, 2);
    ASSERT_EQ(cab.folders().size(), 1u);
    EXPECT_EQ(cab.folders()[0].compression, cabinet::CompressionType::MsZip);
    EXPECT_EQ(cab.folders()[0].data_block_count, 3);

    ASSERT_EQ(cab.files().size(), 2u);
    EXPECT_EQ(cab.files()[0].name, "alpha.bin");
    EXPECT_EQ(cab.files()[0].size, 40000u);
    EXPECT_EQ(cab.files()[0].folder_offset, 0u);
    EXPECT_EQ(cab.files()[1].name, "beta.bin");
    EXPECT_EQ(cab.files()[1].folder_offset, 40000u);
}

TEST(Cabinet, DecompressesAnMsZipFolderAcrossBlockBoundaries) {
    const std::vector<u8> image = from_base64(kCabinetBase64);
    auto parsed = cabinet::Cabinet::parse(std::span<const u8>(image.data(), image.size()));
    ASSERT_TRUE(parsed.is_ok());

    auto folder = parsed.value().extract_folder(0);
    ASSERT_TRUE(folder.is_ok()) << "MSZIP folder failed to decompress";
    EXPECT_EQ(folder.value(), expected_payload());
}

TEST(Cabinet, ExtractsIndividualFilesAtTheirFolderOffsets) {
    const std::vector<u8> image = from_base64(kCabinetBase64);
    auto parsed = cabinet::Cabinet::parse(std::span<const u8>(image.data(), image.size()));
    ASSERT_TRUE(parsed.is_ok());
    const std::vector<u8> payload = expected_payload();

    auto alpha = parsed.value().extract_file_by_name("alpha.bin");
    ASSERT_TRUE(alpha.is_ok());
    EXPECT_EQ(alpha.value(),
              std::vector<u8>(payload.begin(), payload.begin() + 40000));

    // beta.bin starts 40000 bytes in, i.e. inside the *second* CFDATA block,
    // so a decoder that restarts its history per block corrupts this file
    // while leaving alpha.bin intact.
    auto beta = parsed.value().extract_file_by_name("beta.bin");
    ASSERT_TRUE(beta.is_ok());
    EXPECT_EQ(beta.value(),
              std::vector<u8>(payload.begin() + 40000, payload.end()));
}

TEST(MsZip, RejectsABlockWithoutTheCkSignature) {
    // Without the signature check a caller feeding raw DEFLATE would appear to
    // work on stored blocks and fail unpredictably elsewhere.
    mszip::Decoder decoder;
    const std::vector<u8> junk = {0x00, 0x00, 0x01, 0x02};
    std::vector<u8> out;
    auto result = decoder.decode_chunk(std::span<const u8>(junk.data(), junk.size()), 4, out);
    EXPECT_TRUE(result.is_err());
    EXPECT_TRUE(out.empty());
}

TEST(MsZip, ShortOutputIsAnErrorRatherThanAPartialSuccess) {
    // A chunk that decodes to fewer bytes than cbUncomp means a truncated
    // image; reporting success would hand the caller a silently short file.
    const std::vector<u8> image = from_base64(kCabinetBase64);
    auto parsed = cabinet::Cabinet::parse(std::span<const u8>(image.data(), image.size()));
    ASSERT_TRUE(parsed.is_ok());
    auto blocks = parsed.value().enumerate_blocks(0);
    ASSERT_TRUE(blocks.is_ok());
    ASSERT_FALSE(blocks.value().empty());

    const cabinet::DataBlock& first = blocks.value()[0];
    std::span<const u8> payload(image.data() + first.payload_offset, first.compressed_size);

    mszip::Decoder decoder;
    std::vector<u8> out;
    auto result = decoder.decode_chunk(payload, first.uncompressed_size - 1, out);
    EXPECT_TRUE(result.is_err());
}
