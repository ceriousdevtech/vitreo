"""Write crypt_legacy_sigalg_certs.h: a throwaway RSA root whose self-signature
is md5WithRSAEncryption (1.2.840.113549.1.1.4) and a leaf it signs with the
OIW sha1RSASign OID (1.3.14.3.2.29). Windows judges them
(crypt_legacy_sigalg_probe.c -> crypt_legacy_sigalg_probe.expected).

Usage: crypt_legacy_sigalg_certs.py <out.h>
"""
import datetime
import sys

from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import padding, rsa
from cryptography.x509.oid import NameOID

SHA256_RSA = bytes.fromhex("300d06092a864886f70d01010b0500")
MD5_RSA = bytes.fromhex("300d06092a864886f70d0101040500")
OIW_SHA1_RSA = bytes.fromhex("3009060" "52b0e03021d0500")


def der_len(n):
    if n < 0x80:
        return bytes([n])
    b = n.to_bytes((n.bit_length() + 7) // 8, "big")
    return bytes([0x80 | len(b)]) + b


def tlv(tag, content):
    return bytes([tag]) + der_len(len(content)) + content


def body(der):
    """Contents of a DER TLV."""
    n = der[1]
    if n < 0x80:
        return der[2:]
    k = n & 0x7F
    return der[2 + k:]


def resign(cert, key, alg_id, hash_alg):
    tbs = body(cert.tbs_certificate_bytes)
    assert SHA256_RSA in tbs
    tbs = tlv(0x30, tbs.replace(SHA256_RSA, alg_id, 1))
    signature = key.sign(tbs, padding.PKCS1v15(), hash_alg)
    return tlv(0x30, tbs + alg_id + tlv(0x03, b"\x00" + signature))


def main():
    now = datetime.datetime(2026, 1, 1, tzinfo=datetime.timezone.utc)
    later = now + datetime.timedelta(days=3650)
    root_key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    root_name = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, "Vitreo MD5 Probe Root")])
    root = (x509.CertificateBuilder().subject_name(root_name).issuer_name(root_name)
            .public_key(root_key.public_key()).serial_number(0x6001)
            .not_valid_before(now).not_valid_after(later)
            .add_extension(x509.BasicConstraints(ca=True, path_length=None), critical=True)
            .sign(root_key, hashes.SHA256()))
    leaf_key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    leaf = (x509.CertificateBuilder()
            .subject_name(x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, "vitreo-oiw-probe.test")]))
            .issuer_name(root_name).public_key(leaf_key.public_key()).serial_number(0x6002)
            .not_valid_before(now).not_valid_after(later)
            .sign(root_key, hashes.SHA256()))
    root_md5 = resign(root, root_key, MD5_RSA, hashes.MD5())
    leaf_oiw = resign(leaf, root_key, OIW_SHA1_RSA, hashes.SHA1())
    out = ["// Generated by oracle/crypt_legacy_sigalg_certs.py (throwaway test PKI).", "#pragma once"]
    for name, der in (("kMd5RootDer", root_md5), ("kOiwLeafDer", leaf_oiw)):
        out.append(f"static constexpr unsigned char {name}[] = {{")
        for i in range(0, len(der), 16):
            out.append("    " + ", ".join(f"0x{b:02x}" for b in der[i:i + 16]) + ",")
        out.append("};")
    open(sys.argv[1], "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
