#!/usr/bin/env python3
"""Generate tests/winapi/crypt32/pfx_is_pfx_blob_oracle.inc from the Windows
outputs of pfx_is_pfx_blob_probe.c (x86 and x64). The case bytes are parsed
from the probe source, so the probe stays the single statement of them.

    gen_pfx_is_pfx_blob_oracle.py           rewrite the .inc
    gen_pfx_is_pfx_blob_oracle.py --check   fail if the .inc is stale
"""
from pathlib import Path
import re
import sys

here = Path(__file__).resolve().parent
probe = (here / 'pfx_is_pfx_blob_probe.c').read_text()
target = here.parent / 'pfx_is_pfx_blob_oracle.inc'

body = re.search(r'cases\[\]\[2\] = \{(.*?)\n\};', probe, re.S).group(1)
cases = dict(re.findall(r'\{"([^"]+)", "([0-9a-f]*)"\}', body))

rows = {}
for bits in (32, 64):
    rows[bits] = [l.split('\t') for l in
                  (here / f'pfx_is_pfx_blob_probe{bits}.expected').read_text().splitlines()]
assert rows[32] == rows[64], 'x86 and x64 disagree; the .inc needs a per-width table'

out = ['// Generated by tests/winapi/crypt32/oracle/gen_pfx_is_pfx_blob_oracle.py from',
       '// real-Windows crypt32.dll outputs (pfx_is_pfx_blob_probe{32,64}.expected,',
       '// identical at both widths). last_error: GetLastError after the call,',
       '// prefilled 0xDEADBEEF.',
       'struct PfxOracleCase { const char* name; const char* hex; u32 ret; u32 last_error; };',
       'static constexpr PfxOracleCase kPfxOracleCases[] = {']
children = []
for name, ret, err in rows[64]:
    if ret == 'exit':
        children.append((name[len('child_'):], err))
        continue
    hexs = '' if name == 'null_pb_cb0' else cases[name]
    if name != 'null_pb_cb0':
        assert name in cases, name
    out.append('    {"%s", "%s", %s, 0x%su},' % (name, hexs, ret, err))
out += ['};',
        '// Child-process cases: the process exit code (0xC0000005 = the call',
        '// faulted with an access violation, else the BOOL it returned).',
        'struct PfxOracleChild { const char* mode; u32 exit_code; };',
        'static constexpr PfxOracleChild kPfxOracleChildren[] = {']
for mode, code in children:
    out.append('    {"%s", 0x%su},' % (mode, code))
out += ['};', '']
text = '\n'.join(out)

if '--check' in sys.argv:
    if not target.exists() or target.read_text() != text:
        sys.exit(f'{target} is stale; rerun {Path(__file__).name}')
else:
    target.write_text(text)
