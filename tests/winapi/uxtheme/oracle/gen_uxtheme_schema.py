#!/usr/bin/env python3
"""Generate src/winapi/ui/uxtheme/theme_schema.inc from the Windows SDK.

Usage: gen_uxtheme_schema.py <vsstyle.h> <vssym32.h> > theme_schema.inc

Inputs are the 10.0.26100.0 SDK headers (winoracle: C:\\Program Files (x86)\\
Windows Kits\\10\\Include\\10.0.26100.0\\um\\). Emits, for each class uxtheme
draws, its VSCLASS_ name and its parts and states enums as constants in a
per-class namespace, plus every TMT_ property id from vssym32.h.
"""
import re
import sys

CLASSES = ["BUTTON", "EDIT", "COMBOBOX", "SCROLLBAR", "SPIN", "TAB", "PROGRESS",
           "TRACKBAR", "TOOLBAR", "REBAR", "HEADER", "LISTVIEW", "TREEVIEW", "MENU",
           "TOOLTIP", "STATUS", "WINDOW"]


def main():
    vsstyle = open(sys.argv[1], encoding="utf-8", errors="replace").read()
    vssym = open(sys.argv[2], encoding="utf-8", errors="replace").read()
    out = ["// Generated by tests/winapi/uxtheme/oracle/gen_uxtheme_schema.py from the",
           "// 10.0.26100.0 SDK vsstyle.h and vssym32.h. Do not edit.", ""]
    blocks = re.split(r"#ifndef VSCLASS_", vsstyle)
    found = {}
    for b in blocks:
        m = re.match(r"(\w+)\s*\n#define VSCLASS_\w+\s+L\"(\w+)\"", b)
        if not m or m.group(1) not in CLASSES:
            continue
        found[m.group(1)] = (m.group(2), b)
    missing = [c for c in CLASSES if c not in found]
    if missing:
        sys.exit("classes not found: %s" % missing)
    out.append("#ifdef VITREO_UXTHEME_CLASS_TABLE")
    for c in CLASSES:
        name, b = found[c]
        parts = re.search(r"enum \w+PARTS \{(.*?)\};", b, re.S)
        maxpart = max([int(v) for v in re.findall(r"= (\d+)", parts.group(1))] or [0]) if parts else 0
        states = [int(v) for em in re.finditer(r"enum \w+STATES \{(.*?)\};", b, re.S)
                  for v in re.findall(r"= (\d+)", em.group(1))]
        out.append('VITREO_UXTHEME_CLASS(%s, u"%s", %d, %d)' % (c.capitalize(), name, maxpart,
                                                                max(states or [1])))
    out.append("#else")
    for c in CLASSES:
        name, b = found[c]
        out.append("namespace %s {" % c.lower())
        for em in re.finditer(r"enum (\w+) \{(.*?)\};", b, re.S):
            for n, v in re.findall(r"(\w+) = (\d+)", em.group(2)):
                out.append("inline constexpr i32 %s = %s;  // %s" % (n, v, em.group(1)))
        out.append("}  // namespace %s" % c.lower())
    out.append("namespace tmt {")
    for n, v in re.findall(r"#define TMT_(\w+)\s+(\d+)\s*$", vssym, re.M):
        out.append("inline constexpr i32 %s = %s;" % (n, v))
    out.append("}  // namespace tmt")
    out.append("#endif")
    print("\n".join(out))


if __name__ == "__main__":
    main()
