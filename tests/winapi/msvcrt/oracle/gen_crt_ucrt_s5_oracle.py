#!/usr/bin/env python3
"""Generate tests/winapi/msvcrt/crt_ucrt_s5_oracle.inc from the saved Windows
outputs of crt_ucrt_s5_probe.c (x86 and x64). The case inputs are parsed from
the probe source itself, so the probe stays the single statement of them.

    gen_crt_ucrt_s5_oracle.py           rewrite the .inc
    gen_crt_ucrt_s5_oracle.py --check   fail if the .inc is stale
"""
from pathlib import Path
import re
import sys

here = Path(__file__).resolve().parent
probe = (here / 'crt_ucrt_s5_probe.c').read_text()
target = here.parent / 'crt_ucrt_s5_oracle.inc'


def table(name):
    body = re.search(name + r'\[\] = \{(.*?)\n\s*\};', probe, re.S).group(1)
    rows = re.findall(r'\{([^{}]*)\}', body)
    return [[('T' if x.strip() == 'T' else int(x.strip(), 0)) for x in r.split(',')] for r in rows]


conv_cases = table('cases')
bsearch_cases = table('bc')
rows = {}
for bits in (32, 64):
    rows[bits] = [l.split('\t') for l in (here / f'crt_ucrt_s5_probe{bits}.expected').read_text().splitlines()]
assert len(rows[32]) == len(rows[64])

ones = {32: 0xFFFFFFFF, 64: 0xFFFFFFFFFFFFFFFF}
pattern = {32: 0x5A5A5A5A, 64: 0x5A5A5A5A5A5A5A5A}


def size_value(bits, v):
    """Map a pointer-sized *pReturnValue to a bitness-free encoding."""
    if v == ones[bits]:
        return 'kAllOnes'
    if v == pattern[bits]:
        return 'kUntouched'
    return hex(v) + 'ull'


out = ['// Generated by tests/winapi/msvcrt/oracle/gen_crt_ucrt_s5_oracle.py from',
       '// real-Windows ucrtbase.dll outputs (crt_ucrt_s5_probe{32,64}.expected).',
       'constexpr u64 kAllOnes = ~u64{0};       // (size_t)-1 at either width',
       'constexpr u64 kUntouched = 0x5a5a5a5a5a5a5a5aull;  // prefill, never written',
       'constexpr u64 kTrunc = ~u64{0};          // _TRUNCATE',
       'struct S5ConvCase { u32 dst; u64 size; u32 src; u64 count; u32 null_ret; };',
       'static constexpr S5ConvCase kS5ConvCases[] = {']
for c in conv_cases:
    out.append('    {' + ', '.join('kTrunc' if x == 'T' else str(x) for x in c) + '},')
out += ['};',
        '// fn 0 mbstowcs_s, 1 mbsrtowcs_s, 2 wcsrtombs_s. off: units the source',
        '// pointer advanced, 0xffff = set to NULL, 0xeeee = not observed.',
        'struct S5ConvOracle { u32 fn, cse, ret, err, iph_calls, iph_errno; u64 retval; u32 off, lasterr; u16 buf[8]; };',
        'static constexpr S5ConvOracle kS5ConvOracle[] = {']
for a, b in zip(rows[32], rows[64]):
    if a[0] not in ('0', '1', '2'):
        continue
    va = [int(x, 16) for x in a]
    vb = [int(x, 16) for x in b]
    ra, rb = size_value(32, va[6]), size_value(64, vb[6])
    assert ra == rb and va[:6] == vb[:6] and va[7:] == vb[7:], (a, b)
    assert va[8] == 0 and va[9] == 0, 'mbstate must stay untouched'
    out.append('    {%s, %s, {%s}},' % (', '.join(str(x) for x in va[:6]), ra + ', ' + hex(va[7]) + 'u, ' + hex(va[10]) + 'u',
                                       ', '.join(hex(x) for x in va[11:19])))
out += ['};',
        'struct S5BsearchCase { i32 key; u32 null_key, null_base; u64 number, width; u32 null_cmp; };',
        'static constexpr S5BsearchCase kS5BsearchCases[] = {']
for c in bsearch_cases:
    out.append('    {' + ', '.join(str(x) for x in c) + '},')
out += ['};',
        '// index 0xff = NULL; visited = element indices probed, one nibble each.',
        'struct S5BsearchOracle { u32 cse, index, err, iph_calls, iph_errno, cmp_calls, cmp_bad, visited; };',
        'static constexpr S5BsearchOracle kS5BsearchOracle[] = {']
for a, b in zip(rows[32], rows[64]):
    if a[0] != 'b':
        continue
    assert a == b, (a, b)
    out.append('    {' + ', '.join(hex(int(x, 16)) + 'u' for x in a[1:]) + '},')
out += ['};',
        'struct S5MinMaxOracle { const char* name; u32 i, j; u64 result32, result64; u32 flags32, flags64; };',
        'static constexpr S5MinMaxOracle kS5MinMaxOracle[] = {']
for a, b in zip(rows[32], rows[64]):
    if a[0] != 'm':
        continue
    assert a[1:4] == b[1:4], (a, b)
    out.append('    {"%s", %s, %s, %sull, %sull, %su, %su},' % (
        a[1], int(a[2], 16), int(a[3], 16), hex(int(a[4], 16)), hex(int(b[4], 16)), hex(int(a[5], 16)), hex(int(b[5], 16))))
out += ['};']

m = re.search(r'dinputs\[\] = \{([^}]+)\}', probe).group(1)
out.append('static constexpr u64 kS5DoubleInputs[] = {' + ', '.join(
    hex(int(re.sub(r'[uUlL]+$', '', x.strip()), 0)) + 'ull' for x in m.split(',')) + '};')
m = re.search(r'finputs\[\] = \{([^}]+)\}', probe).group(1)
out.append('static constexpr u32 kS5FloatInputs[] = {' + ', '.join(
    hex(int(re.sub(r'[uUlL]+$', '', x.strip()), 0)) + 'u' for x in m.split(',')) + '};')

content = '\n'.join(out) + '\n'
if '--check' in sys.argv:
    if not target.exists() or target.read_text() != content:
        raise SystemExit(f'Generated oracle table is stale: {target}')
else:
    target.write_text(content)
