#!/usr/bin/env python3
"""Generate tests/winapi/msvcrt/crt_ucrt_s6_oracle.inc from the saved Windows
outputs of crt_ucrt_s6_probe.c (x86 and x64). The case inputs are parsed from
the probe source itself, so the probe stays the single statement of them.

    gen_crt_ucrt_s6_oracle.py           rewrite the .inc
    gen_crt_ucrt_s6_oracle.py --check   fail if the .inc is stale
"""
from pathlib import Path
import re
import sys

here = Path(__file__).resolve().parent
probe = (here / 'crt_ucrt_s6_probe.c').read_text()
target = here.parent / 'crt_ucrt_s6_oracle.inc'

rows = {}
for bits in (32, 64):
    rows[bits] = [l.split('\t') for l in
                  (here / f'crt_ucrt_s6_probe{bits}.expected').read_text().splitlines()]
assert rows[32] == rows[64], 'x86 and x64 disagree; the .inc needs a per-width table'
rows = rows[64]

NARROW = r'(?:"(?:[^"\\]|\\.)*"\s*)+'


def unescape(body):
    """C string literal body (one or more adjacent quoted pieces) -> code units."""
    out = []
    for piece in re.findall(r'"((?:[^"\\]|\\.)*)"', body):
        i = 0
        while i < len(piece):
            c = piece[i]
            if c != '\\':
                out.append(ord(c))
                i += 1
                continue
            e = piece[i + 1]
            if e == 'x':
                m = re.match(r'[0-9a-fA-F]+', piece[i + 2:])
                out.append(int(m.group(0), 16))
                i += 2 + len(m.group(0))
            elif e in '01234567':
                m = re.match(r'[0-7]{1,3}', piece[i + 1:])
                out.append(int(m.group(0), 8))
                i += 1 + len(m.group(0))
            else:
                out.append({'r': 13, 'n': 10, 't': 9, '\\': 92, '"': 34}[e])
                i += 2
    return out


def table(name):
    return re.search(name + r'\[\](?:\[\d+\])?\s*=\s*\{(.*?)\n\s*\};', probe, re.S).group(1)


def units(values):
    return '{' + ', '.join(hex(v) for v in values + [0]) + '}'


out = ['// Generated by tests/winapi/msvcrt/oracle/gen_crt_ucrt_s6_oracle.py from',
       '// real-Windows ucrtbase.dll outputs (crt_ucrt_s6_probe{32,64}.expected,',
       '// identical at both widths).', '']

# ---- quick_exit children ----
out += ['struct S6Quick { const char* mode; const char* output; u32 exit_code; };',
        'static constexpr S6Quick kS6Quick[] = {']
for r in rows:
    if r[0] == 'q':
        out.append('    {"%s", "%s", 0x%su},' % (r[1], '' if r[2] == '-' else r[2], r[3]))
out += ['};', '']

# ---- _wcsicoll ----
coll = []
for a, b in re.findall(r'\{\s*(0|L"(?:[^"\\]|\\.)*")\s*,\s*(0|L"(?:[^"\\]|\\.)*")\s*\}', table('coll')):
    coll.append((None if a == '0' else unescape(a[1:]), None if b == '0' else unescape(b[1:])))
irows = [r for r in rows if r[0] == 'i']
assert len(irows) == len(coll)
out += ['// a/b: UTF-16 strings, nullptr = NULL argument.',
        'struct S6Coll { bool null_a, null_b; u16 a[8]; u16 b[8]; u32 ret, err, iph_calls, iph_errno; };',
        'static constexpr S6Coll kS6Coll[] = {']
for (a, b), r in zip(coll, irows):
    out.append('    {%s, %s, %s, %s, 0x%su, 0x%su, 0x%su, 0x%su},' % (
        'true' if a is None else 'false', 'true' if b is None else 'false',
        units(a or []), units(b or []), r[2], r[3], r[4], r[5]))
out += ['};', '']

# ---- strtok_s ----
seqs = re.findall(r'\{\s*(' + NARROW + r')\s*,\s*(' + NARROW + r')\s*,\s*(\d+)\s*\}', table('seqs'))
out += ['struct S6TokSeq { u8 text[16]; u8 delims[8]; u32 steps; };',
        'static constexpr S6TokSeq kS6TokSeqs[] = {']
for text, delims, steps in seqs:
    out.append('    {%s, %s, %s},' % (units(unescape(text)), units(unescape(delims)), steps))
out += ['};',
        '// ret/ctx: offsets into the buffer (0x100+ = into the second buffer),',
        '// ret 0xff = NULL, ctx 0xffff = NULL. Cases 0x10+ are the probe\'s',
        '// error cases, in its order.',
        'struct S6TokRow { u32 cse, step, ret, ctx, err, iph_calls, iph_errno; u32 n; u8 buf[16]; };',
        'static constexpr S6TokRow kS6TokRows[] = {']
for r in rows:
    if r[0] == 't':
        buf = [int(x, 16) for x in r[8:]]
        out.append('    {0x%s, %s, 0x%s, 0x%s, 0x%su, 0x%su, 0x%su, %d, {%s}},' % (
            r[1], r[2], r[3], r[4], r[5], r[6], r[7], len(buf), ', '.join(hex(x) for x in buf)))
out += ['};', '']

# ---- __stdio_common_vfwscanf ----
wc = re.findall(r'\{\s*(' + NARROW + r')\s*,\s*(\d+)\s*,\s*"([^"]*)"\s*,\s*(\d+)\s*,\s*L("(?:[^"\\]|\\.)*")\s*,\s*(\d+)\s*\}',
                table('wc'))
out += ['struct S6ScanCase { u8 bytes[16]; u32 n; const char* mode; u64 options; u16 format[16]; u32 kind; };',
        'static constexpr S6ScanCase kS6ScanCases[] = {']
for bytes_, n, mode, opts, fmt, kind in wc:
    b = unescape(bytes_)
    assert len(b) >= int(n), (bytes_, n)
    out.append('    {%s, %s, "%s", %s, %s, %s},' % (units(b[:int(n)]), n, mode, opts, units(unescape(fmt)), kind))
out += ['};',
        '// cse 0x20 = NULL stream, 0x21 = NULL format. next: fgetc after the call.',
        'struct S6ScanRow { u32 cse, ret, err, iph_calls, iph_errno; u64 v[4]; u32 next; };',
        'static constexpr S6ScanRow kS6ScanRows[] = {']
for r in rows:
    if r[0] == 'w':
        out.append('    {0x%s, 0x%su, 0x%su, 0x%su, 0x%su, {0x%sull, 0x%sull, 0x%sull, 0x%sull}, 0x%su},' % tuple(r[1:]))
out += ['};', '']

# ---- qsort_s ----
vc = re.findall(r'\{\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\}', table('vc'))
out += ['struct S6SortValidation { u32 null_base; u64 number, width; u32 null_cmp; };',
        'static constexpr S6SortValidation kS6SortValidation[] = {']
for v in vc:
    out.append('    {%s, %s, %s, %s},' % v)
out += ['};',
        '// cse < 0x20: validation case (elements = the {3, 1, 2} array after);',
        '// 0x20 ints, 0x21 3-byte records, 0x22 one element (cmp_calls is a',
        '// 0/1 "was called" flag for 0x20/0x21).',
        'struct S6SortRow { u32 cse, err, iph_calls, iph_errno, cmp_calls, cmp_bad; u32 n; u32 elems[16]; };',
        'static constexpr S6SortRow kS6SortRows[] = {']
for r in rows:
    if r[0] == 's':
        el = r[7:]
        out.append('    {0x%s, 0x%su, 0x%su, 0x%su, 0x%su, 0x%su, %d, {%s}},' % (
            r[1], r[2], r[3], r[4], r[5], r[6], len(el), ', '.join('0x%su' % x for x in el)))
out += ['};', '']

text = '\n'.join(out)
if '--check' in sys.argv:
    if not target.exists() or target.read_text() != text:
        sys.exit(f'{target} is stale; rerun {Path(__file__).name}')
else:
    target.write_text(text)
